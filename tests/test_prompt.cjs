const assert=require('node:assert/strict');
const fs=require('node:fs');
const {buildPrompt}=require('../web/prompt.js');
const catalog=JSON.parse(fs.readFileSync('data/catalog.json','utf8'));
const curation=JSON.parse(fs.readFileSync('data/curation.json','utf8'));
const components=curation.map(choice=>{
  const source=catalog.sources.find(s=>s.components.some(c=>c.id===choice.id));
  return {...source.components.find(c=>c.id===choice.id),source:source.name,curation:choice};
});
const prompt=buildPrompt([...components,components[0]],{project:'Un portfolio pour Camille',style:'Vert sauge et ivoire',notes:{[components[0].id]:'Dans la section témoignages'}});
assert.ok(prompt.includes(`COMPOSANTS À INTÉGRER (${components.length})`));
for(const c of components){assert.ok(prompt.includes(c.url));assert.equal(prompt.split('Identifiant : '+c.id).length,2);assert.ok(prompt.includes(c.curation.interaction));}
assert.ok(prompt.includes('Un portfolio pour Camille'));
assert.ok(prompt.includes('Dans la section témoignages'));
assert.ok(prompt.includes('sans redirection'));
assert.ok(prompt.includes('prefers-reduced-motion'));
assert.equal(buildPrompt([]),'');
const staticPrompt=buildPrompt([{id:'one',name:'Static',source:'Example',url:'https://example.com/component',kind:'Composant'}]);
assert.ok(staticPrompt.includes('n’a pas de démonstration locale validée'));
assert.ok(!staticPrompt.includes('undefined'));
console.log('PASS: all curated components, deduplication, sources, custom brief and notes, static fallback, empty selection');
const visual=JSON.parse(fs.readFileSync('data/reference_sources.json','utf8'))[0].components[0];
const mixed=buildPrompt([components[0],{...visual,source:'One Prompt Design'}]);
assert.ok(mixed.includes(visual.url));
assert.ok(mixed.includes('ce n’est pas un composant React'));
assert.ok(mixed.includes('proposer un visuel original'));
assert.ok(mixed.includes('Auteur indiqué'));
const visuals=JSON.parse(fs.readFileSync('data/reference_sources.json','utf8'))[0].components;
const composed=buildPrompt([components[0],visuals[0],visuals[1],visuals[0]],{notes:{[visuals[0].id]:'Fond du hero',[components[0].id]:'Au-dessus du fond du hero'}});
assert.ok(composed.includes('2 fond(s) + 1 composant(s)'));
assert.equal(composed.split('Rôle : FOND / ARRIÈRE-PLAN').length-1,2);
assert.ok(composed.includes('Fond du hero'));
assert.ok(composed.includes('Au-dessus du fond du hero'));
assert.ok(composed.includes('ne doivent pas capter les clics'));
for(const item of [components[0],visuals[0],visuals[1]])assert.equal(composed.split('Identifiant : '+item.id).length-1,1);
assert.ok(buildPrompt([visuals[0]]).includes('1 fond(s) + 0 composant(s)'));
console.log('PASS: mixed backgrounds and UI, placement instructions, multiple backgrounds, deduplication and backgrounds alone');
